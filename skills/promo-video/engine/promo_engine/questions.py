"""The opening questions, computed from what is already known. Ask once; never re-ask.

`plan()` looks at the run config, the product scan and the environment and returns only the
decisions that are still open. Anything supplied with the command (recorded in
`config.decided` by `promo init`) or evidenced by the repository is not asked again. The
agent asks the returned questions in one batch, then records the answers with `promo init`.
"""
from __future__ import annotations

from . import providers
from .config import ASPECTS, Workspace, mode
from .util import read_json

REFERENCE_Q = ("Do you have a promotional video you want to use as inspiration? "
               "Paste its URL or local file path, or say no.")
AUDIO_Q = ("Would you like AI voice-over and professional sound effects? There will be no background "
           "music. If you want AI voice-over, do you already have an OpenRouter or OpenAI API key "
           "configured in the environment?")


def _product_known(cfg: dict, scan: dict | None) -> tuple[bool, str]:
    if cfg["product"].get("name"):
        return True, "name given"
    if not scan:
        return False, "the repository has not been scanned yet (run `promo scan` first)"
    readme = scan.get("readme") or {}
    names = [readme.get("title")] + [m.get("name") for m in (scan.get("manifests") or {}).values()]
    descs = [readme.get("intro")] + [m.get("description") for m in (scan.get("manifests") or {}).values()]
    if any(names) and any(descs):
        return True, "README / manifest name and description"
    return False, "the repository does not state the product's name and purpose"


def _assets_known(ws: Workspace, scan: dict | None) -> bool:
    assets = (scan or {}).get("assets") or {}
    in_repo = any(assets.get(k) for k in ("logos", "screenshots", "images", "videos"))
    in_ws = ws.assets.is_dir() and any(p.is_file() for p in ws.assets.rglob("*"))
    return in_repo or in_ws


def plan(ws: Workspace, env=None) -> list[dict]:
    cfg = ws.config()
    decided = set(cfg.get("decided") or [])
    scan = read_json(ws.scan) if ws.scan.exists() else None
    out: list[dict] = []

    if "reference" not in decided:
        out.append({"id": "reference", "question": REFERENCE_Q, "answer": "promo init --reference <url|path|none>",
                    "why": "decides the mode: a reference → reference-driven film, none → autonomous film"})
    if "audio" not in decided:
        out.append({"id": "audio", "question": AUDIO_Q, "answer": "promo init --audio voiceover|effects|silent",
                    "options": [
                        {"value": "voiceover", "label": "A. Voice-over plus professional sound effects"},
                        {"value": "effects", "label": "B. Professional sound effects only, no narration"},
                        {"value": "silent", "label": "C. Completely silent: no voice-over, effects or music"}],
                    "why": "the audio policy is fixed before any audio is generated"})
    elif cfg["audio"]["voiceover"] and "provider" not in decided:
        res = providers.resolve(cfg["voice"]["provider"], env)
        if res.provider is None:
            opts = [{"value": p, "label": p} for p in (res.configured or [])] + \
                   [{"value": p, "label": f"{p} (local, keyless)"} for p in res.local] + \
                   [{"value": "files", "label": "files (my own recordings in promo/assets/vo/)"}]
            out.append({"id": "provider", "question": f"Which voice engine should narrate? {res.reason}.",
                        "answer": "promo init --provider <name>", "options": opts,
                        "why": "voice is never generated by a provider you did not choose"})
    if "product" not in decided:
        known, why = _product_known(cfg, scan)
        if not known:
            out.append({"id": "product", "question": "What is the product called, and what does it do?",
                        "answer": "promo init --name '<name>' (and describe it)", "why": why})
    if scan is not None and not _assets_known(ws, scan):
        out.append({"id": "assets", "question": "Where are the product's screenshots and logo? "
                    "(a folder path, 'capture' to screenshot the running app, or 'none')",
                    "answer": "copy into promo/assets/ or run `promo capture`",
                    "why": "the scan found no screenshots, logos or recordings"})
    if "formats" not in decided:
        out.append({"id": "formats", "question": "Which formats do you need?",
                    "answer": "promo init --formats 16:9 9:16 store-portrait ...",
                    "options": [{"value": a, "label": f"{a} ({v['width']}×{v['height']})"} for a, v in ASPECTS.items()],
                    "why": "only requested formats are rendered"})
    if "runtime" not in decided and mode(cfg) == "autonomous":
        out.append({"id": "runtime", "question": "Roughly how long should the film be?",
                    "answer": "promo init --runtime 30-45",
                    "why": "with no reference, nothing in the input sets the length (default 60–100 s)"})
    return out

